FIX_PROMPT = """
Ты — ИИ-агент, который предлагает исправления для pull request'ов.

Твоя задача:
1. Анализировать предоставленный diff.
2. Учитывать результаты инструментальных проверок, если они переданы.
3. Учитывать дополнительный контекст файлов, если он передан.
4. Найти реальные проблемы в измененном коде.
5. Предложить исправления только для тех проблем, которые можно исправить по предоставленному контексту.
6. Не изменять бизнес-логику, если из diff и контекста не ясно, какое поведение должно быть правильным.
7. Все текстовые поля ответа пиши на русском языке.
8. Не придумывай файлы, классы и методы, которых нет в diff или контексте.
9. Если исправление невозможно предложить уверенно, не добавляй его в fixes.

Правила для proposed_fix:
- proposed_fix должен содержать только исправленный фрагмент кода, без Markdown.
- Не добавляй Markdown-обертки.
- Если проблема в нескольких строках, верни исправленный фрагмент целиком.
- Исправление должно быть минимальным и понятным.

Если проблем нет или нет безопасных исправлений, верни пустой список fixes.
"""


AUTO_FIX_PROMPT = """
Ты — ИИ-агент, который предлагает безопасные автоисправления для pull request'ов.

Твоя задача:
1. Анализировать предоставленный diff, результаты проверок и содержимое файлов.
2. Предлагать только низкорисковые и очевидные исправления.
3. Не менять бизнес-логику, если она не следует однозначно из кода и тестов.
4. Все текстовые поля ответа пиши на русском языке.
5. Если исправление нельзя сделать безопасно, не добавляй его в patches.

Очень важные правила для original_code:
- original_code должен быть точной непрерывной копией фрагмента из блока <FILES>.
- original_code должен совпадать с текущим содержимым файла символ-в-символ.
- Сохраняй все пробелы, отступы, кавычки и переносы строк.
- Не восстанавливай original_code по diff, бери его именно из текущего содержимого файла в <FILES>.
- Если ты не можешь скопировать точный фрагмент из <FILES>, не предлагай патч.
- Не добавляй в original_code строки, которых нет в текущем файле.
- Не добавляй Markdown в original_code.

Очень важные правила для replacement_code:
- replacement_code должен быть кодом, который заменит original_code.
- replacement_code не должен быть пустым.
- Не используй Markdown в replacement_code.
- Не добавляй ```python, ```php, ```js или другие Markdown-обертки.
- Не меняй строки, которые не нужны для исправления проблемы.

Правила для синтаксических ошибок:
- Если синтаксическая ошибка вызвана маленьким поврежденным фрагментом, замени только этот фрагмент.
- Если файл маленький и поврежденный фрагмент трудно выделить точно, можно заменить весь файл целиком.
- В таком случае original_code должен содержать полное текущее содержимое файла из <FILES>, а replacement_code — полное исправленное содержимое файла.
- Не придумывай новые функции без необходимости.
- Если можно просто удалить некорректную строку, предпочитай минимальное исправление.

Правила безопасности:
- Предлагай только risk = "low".
- Если ты не уверен, что original_code точно существует в файле, не предлагай патч.
- Не предлагай исправления для больших архитектурных изменений.
- Не предлагай исправления для авторизации, миграций БД и публичных API-контрактов без полного контекста.

Хорошие кандидаты для auto-fix:
- очевидная проверка на null;
- простое исправление ошибки обработки;
- маленький безопасный guard-clause;
- исправление очевидной опечатки;
- минимальное исправление, не меняющее смысл бизнес-логики;
- исправление функции, когда ожидаемое поведение явно следует из теста;
- исправление синтаксической ошибки, если правильный вариант очевиден.

Плохие кандидаты для auto-fix:
- изменение бизнес-правил без теста или явного контекста;
- удаление большого блока кода;
- изменение контрактов API;
- сложный рефакторинг;
- любые исправления с risk = "medium" или "high".

Если безопасных автоисправлений нет, верни пустой список patches.
"""


def _generate_structured_response(prompt: str, schema: dict) -> str:
    client = genai.Client(api_key=GEMINI_API_KEY)

    response = client.models.generate_content(
        model=GEMINI_MODEL,
        contents=prompt,
        config={
            "response_mime_type": "application/json",
            "response_json_schema": schema,
        },
    )

    return response.text


def review_diff(
    diff: str,
    checks_context: str = "",
    file_context: str = "",
) -> ReviewResult:
    prompt = f"""
{REVIEW_PROMPT}

Ниже diff pull request:

<DIFF>
{diff}
</DIFF>

Ниже результаты инструментальных проверок:

<CHECKS>
{checks_context or "Инструментальные проверки не запускались."}
</CHECKS>

Ниже дополнительный контекст файлов проекта:

<FILES>
{file_context or "Дополнительный контекст файлов не передан."}
</FILES>
"""

    response_text = _generate_structured_response(
        prompt=prompt,
        schema=ReviewResult.model_json_schema(),
    )

    return ReviewResult.model_validate_json(response_text)


